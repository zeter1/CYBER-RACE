// Canonical PNG sources -> data-URI script, so canvas repaint also works on file://.
// This optional generator writes only assets/garage/cars.js.
import {readFileSync,writeFileSync} from 'node:fs';
const data={};
for(const id of ['universal','interceptor','armored'])data[id]='data:image/png;base64,'+readFileSync(new URL('../assets/garage/'+id+'-views.png',import.meta.url)).toString('base64');
writeFileSync(new URL('../assets/garage/cars.js',import.meta.url),'// Generated by scripts/build-garage-art.mjs; edit the PNG sources.\n(()=>{globalThis.CyberRace.ui.garageArtData='+JSON.stringify(data)+';})();\n');
